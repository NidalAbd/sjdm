// Get stored locale or default to 'en'
const storedLocale = localStorage.getItem('locale') || 'en'

const i18n = createI18n({
    legacy: false,
    locale: storedLocale,
    fallbackLocale: 'en',
    messages,
    missing: (locale, key) => {
        // Silent fallback - don't warn for missing keys, vue-i18n falls back to 'en' automatically
        return undefined
    },
})

/**
 * Load translations from API and merge into vue-i18n
 * This enables dynamic, database-driven translations for all 17 languages
 */
export async function loadLocaleMessages(locale) {
    try {
        const response = await fetch(`/api/translations/${locale}`)
        const data = await response.json()

        if (data.success && data.translations) {
            // Convert flat "group.key" format to nested format for vue-i18n
            const nested = {}
            for (const [fullKey, value] of Object.entries(data.translations)) {
                const dotIndex = fullKey.indexOf('.')
                if (dotIndex > -1) {
                    const group = fullKey.substring(0, dotIndex)
                    const key = fullKey.substring(dotIndex + 1)
                    if (!nested[group]) nested[group] = {}
                    nested[group][key] = value
                }
            }

            // Merge with existing messages (API translations override hardcoded ones)
            const existing = i18n.global.getLocaleMessage(locale) || {}
            const merged = { ...existing }
            for (const [group, keys] of Object.entries(nested)) {
                merged[group] = { ...(merged[group] || {}), ...keys }
            }

            i18n.global.setLocaleMessage(locale, merged)
            return true
        }
    } catch (error) {
        console.error(`Failed to load translations for ${locale}:`, error)
    }
    return false
}

export default i18n
